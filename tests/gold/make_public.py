def main():
    os.makedirs(OUT, exist_ok=True)
    slugs = {n[0] for n in NOTES}
    for n in NOTES:
        with open(os.path.join(OUT, f"2026-01-01-{n[0]}.md"), "w") as f:
            f.write(note(*n))
    qs = []
    for q, slug, kind in QUESTIONS:
        assert not slug or slug in slugs, slug
        qs.append({"project": "tidepool", "question": q, "answer": f"memorycastle/journal/2026-01-01-{slug}.md" if slug else "", "kind": kind})
    with open(os.path.join(HERE, "public.json"), "w") as f:
        json.dump({"questions": qs}, f, indent=1)
    print(len(NOTES), "notes,", len(qs), "questions")

main()
