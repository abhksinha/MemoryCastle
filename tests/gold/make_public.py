def note(slug, title, files, dec, rej, meas):
    body = f"# {title}\nAuthor: fixture+claude | Date: 2026-01-{(zlib.crc32(slug.encode()) % 27) + 1:02d}\nFiles: {files}\n\n## Decision\n{dec}\n"
    if rej:
        body += f"\n## Rejected\n- {rej}\n"
    if meas:
        body += f"\n## Measured\n- {meas}\n"
    return body

